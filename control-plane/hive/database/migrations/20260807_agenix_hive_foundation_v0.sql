create or replace function agenix_hive_private.is_org_member(p_org_id uuid)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, agenix_hive
as $$
  select exists (
    select 1 from agenix_hive.memberships m
    where m.organization_id = p_org_id
      and m.user_id = auth.uid()
      and m.status = 'active'
  );
$$;

create or replace function agenix_hive_private.is_any_member()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, agenix_hive
as $$
  select exists (
    select 1 from agenix_hive.memberships m
    where m.user_id = auth.uid()
      and m.status = 'active'
  );
$$;

