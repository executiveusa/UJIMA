create or replace function agenix_hive_private.set_updated_at()
returns trigger language plpgsql security definer set search_path = pg_catalog as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare t text;
begin
  foreach t in array array[
    'organizations','projects','memberships','providers','provider_capabilities','provider_health',
    'state_domains','command_sessions','commands','runs','run_steps','event_deliveries'
  ] loop
    execute format('create trigger %I_set_updated_at before update on agenix_hive.%I for each row execute function agenix_hive_private.set_updated_at()', t, t);
  end loop;
end $$;

